on public.trips for all to authenticated
using (
  owner_id = auth.uid()
  and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
)
with check (
  owner_id = auth.uid()
  and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

